/**
 * Fetch the LKW Swagger JSON from the running API and generate
 * TypeScript types via openapi-typescript. Writes to src/types.gen.ts.
 *
 * Usage:
 *   npm run gen:types                                   # uses default URL
 *   LKW_API_URL=https://api.lkw.digital npm run gen:types
 *   LKW_API_URL=http://localhost:3001 npm run gen:types  # local dev
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '../src/types.gen.ts');

async function main() {
  const baseUrl = process.env.LKW_API_URL ?? 'https://api.lkw.digital';
  const url = new URL('/api-json', baseUrl).toString();

  console.log(`Fetching OpenAPI spec from ${url}...`);
  const ast = await openapiTS(new URL(url));
  const ts = astToString(ast);

  const header =
    '/**\n' +
    ' * AUTO-GENERATED by scripts/gen-types.ts. Do not edit by hand.\n' +
    ' * Source: ' + url + '\n' +
    ' * Regenerate: npm run gen:types\n' +
    ' */\n\n';

  fs.writeFileSync(OUT, header + ts, 'utf-8');
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
